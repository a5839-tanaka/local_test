/*
 * １０のべき乗の絶対値
 *
 * 機能：
 *		基数１０、指数 aData のべき乗を求め、絶対値を返送する。
 * 戻り値：
 *		基数１０、指数aData（絶対値）、のべき乗
 */
long long commfunc_pow10abs( short aData )
{
	int				loopCnt;
	long long		retData = 1;

	if( aData < 0 ) aData *= -1;

	for( loopCnt = 0 ; loopCnt < aData ; loopCnt++ )
		retData *= 10;

	return( retData );
}

