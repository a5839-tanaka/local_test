#!/bin/sh

# 収集装置のデータアップデート用ファイルを生成する。
#
# 収集装置のアップデート用ファイルは必ず / ディレクトリから始まる形式で作成する。
# Linux で普通に tar コマンドを使用すると、アーカイブ対象となるファイルの先頭の / が自動的に削除されてしまう。
# これを回避するため tar コマンドのオプションに -P をつける。
# ＜本ツールが生成するアップデート用ファイル＞
#  DATA_UPDATE_YYYYMMDD_HH.tgz
# 実記に適用する場合は、サーバーの指定ディレクトリ上に 収集装置ID_PROC_UPDATE.tgz の名称で配置する必要がある。
#----------------------------------------------------------------------------------
# 更新履歴
# 

echo "============================================================================="
echo "ＮＫ－ＳＹＳＴＥＭ データ収集装置"
echo "-----------------------------------------------------------------------------"
echo "データアップデート用アーカイブファイル生成ツール"
echo "============================================================================="

if [ "zz${USER}" != "zzroot" ] ; then
	echo "ERROR: ルートユーザ以外はこのツールを起動できません"
	exit
fi

echo "--------------------------------------------"
echo "アップデート用アーカイブ作成を開始しますか？"
echo "--------------------------------------------"
echo -n "( y or n ) >>> "
read WORKDATA
if [ "zzy" != "zz${WORKDATA}" ] ; then
	echo "処理を中止します"
	exit
fi

# 現在時刻の取得
DATEINFO=`date +%Y%m%d_%H`

# アップデート（アーカイブ）ファイル名の決定
TARGETFILE="/home/nksystem/update_package/DATA_UPDATE_${DATEINFO}.tgz"

# 現在のディレクトリの保存
OLDDIR=`pwd`


# アーカイブファイルの生成
echo "・アップデート用アーカイブファイルを生成しています"
# ルートディレクトリに移動
cd /home/nksystem/CSVDATA/
tar cvzPpf ${TARGETFILE} *.csv

# 作業前のディレクトリに移動
cd ${OLDDIR}

# 終了メッセージ
echo "============================================================================="
echo "アップデート用アーカイブファイルの生成が終了致しました"
echo "-----------------------------------------------------------------------------"
echo "ファイル名：${TARGETFILE}"
echo "============================================================================="
